package rc800.lpm.xilinx

import spinal.core._
import spinal.lib._

import rc800.lpm


/** Read-only memory whose contents are written into the description instead of
  * loaded from a file.
  *
  * That difference is the whole reason this implementation exists.  SpinalHDL
  * initialises an inferred memory with `$readmemb`, and a memory whose contents
  * arrive from a file at simulation time is not read-only memory to the mapper:
  * it cannot build a block ROM out of values it has never seen, so the table
  * becomes lookup-table logic.  Here the contents are constant assignments in
  * the emitted module, which the mapper can place in block memory
  * (`rom_style`), and the same text simulates as-is - no vendor library, no
  * second model to keep in step.
  *
  * The clock and its enable are ports because a blackbox has no ambient clock:
  * `mapClockDomain` wires them to the surrounding domain, and refuses to
  * elaborate if the domain has a clock enable (the core's does - the bus grants
  * the processor one main clock in four) and the blackbox does not expose it. */
class Rom(dataWidth: Int, content: Seq[BigInt])
	extends BlackBox
	with lpm.Rom {

	override def width = dataWidth
	override def depth = content.length
	override def init  = content

	require(isPow2(depth), "ROM depth must be a power of two")

	// The read side comes from the trait, and must not be redeclared here: a
	// second bundle would be a different object from the one the caller
	// connects to, and the ports would end up with no driver.  A blackbox also
	// needs the domain's clock signals, which the inferred implementation takes
	// from the ambient domain instead.
	val pins = new Bundle {
		val clk   = in Bool()
		val clkEn = in Bool()
	}

	noIoPrefix()
	mapClockDomain(clock = pins.clk, enable = pins.clkEn)

	setBlackBoxName(s"Rom_${width}x${depth}")
	setInlineVerilog(Rom.verilog(width, init, pinNames))

	/** Port names as this component's Verilog will spell them: `noIoPrefix`
	  * strips the prefix from the read side, while the clock signals sit under
	  * their bundle name. */
	private def pinNames: Rom.Pins =
		Rom.Pins(clk = "pins_clk", clkEn = "pins_clkEn",
			enable = "enable", address = "address", data = "data")
}


/** The port names of the generated module, so its description and its
  * instantiation are produced from one source rather than guessed twice. */
object Rom {
	case class Pins(clk: String, clkEn: String, enable: String, address: String, data: String)

	def verilog(dataWidth: Int, content: Seq[BigInt], pins: Pins): String = {
		val hexWidth = (dataWidth + 3) / 4
		def hex(value: BigInt) = "0" * (hexWidth - value.toString(16).length) + value.toString(16)

		val rows = content.zipWithIndex.map { case (value, address) =>
			f"    rom[$address] = ${dataWidth}'h${hex(value)};"
		}

		s"""|// Generated by rc800.lpm.xilinx.Rom - do not edit.
		    |// Contents are constants in the description so the mapper can place
		    |// this in block memory: a $$readmemb image is not ROM content to it.
		    |module Rom_${dataWidth}x${content.length} (
		    |  input  wire                     ${pins.clk},
		    |  input  wire                     ${pins.clkEn},
		    |  input  wire                     ${pins.enable},
		    |  input  wire [${log2Up(content.length) - 1}:0]                  ${pins.address},
		    |  output reg  [${dataWidth - 1}:0]                  ${pins.data}
		    |);
		    |
		    |  (* rom_style = "block" *) reg [${dataWidth - 1}:0] rom [0:${content.length - 1}];
		    |
		    |  initial begin
		    |${rows.mkString("\n")}
		    |  end
		    |
		    |  always @(posedge ${pins.clk}) begin
		    |    if (${pins.clkEn} && ${pins.enable}) ${pins.data} <= rom[${pins.address}];
		    |  end
		    |endmodule
		    |""".stripMargin
	}
}
